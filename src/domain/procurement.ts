export function isTerminalStatus(status: ProjectStatus | string): boolean {
  return TERMINAL_STATUSES.includes(status as ProjectStatus);
}

export function isActiveProject(project: Pick<ProjectRecord, 'status'>): boolean {
  return !isTerminalStatus(project.status);
}

export function hasTorTabData(
  project: Pick<ProjectRecord, 'reference' | 'projectDetails' | 'files'>,
): boolean {
  const details = project.projectDetails || {};
  const files = project.files || [];
  return Boolean(
    details.torOrderNo?.trim() ||
      details.torOrderDate ||
      details.torPreparedDate ||
      details.torDate ||
      details.referenceDate ||
      details.torNo?.trim() ||
      details.torAuthor?.trim() ||
      details.torNotes?.trim() ||
      Number(project.reference) > 0 ||
      (details.torMembers || []).some((m) => m.name?.trim()) ||
      files.some((f) => f.category === 'tor'),
  );
}

export function getInboxProjects(rows: ProjectRecord[], userId: string): ProjectRecord[] {
  return rows.filter(
    (r) => r.assignee === userId && isActiveProject(r) && hasTorTabData(r),
  );
}

export function generateNextProjectCode(
  rows: ProjectRecord[],
  type: ProjectType,
): string {
  const prefix = type === 'ซื้อ' ? 'ซ.' : type === 'จ้าง' ? 'จ.' : '';
  if (!prefix) return '';

  const pattern = type === 'ซื้อ' ? /^ซ\.\s*(\d+)$/ : /^จ\.\s*(\d+)$/;
  let maxSeq = 0;

  for (const r of rows) {
    const match = String(r.code || '').trim().match(pattern);
    if (match) {
      const seq = Number(match[1]);
      if (Number.isInteger(seq) && seq > maxSeq) {
        maxSeq = seq;
      }
    }
  }

  const existingKeys = new Set(rows.map((r) => normalizeCodeKey(r.code)));
  let candidateSeq = maxSeq + 1;
  while (
    existingKeys.has(
      normalizeCodeKey(`${prefix}${String(candidateSeq).padStart(3, '0')}`),
    )
  ) {
    candidateSeq += 1;
  }

  return `${prefix}${String(candidateSeq).padStart(3, '0')}`;
}

export function isAutoGeneratedProjectCode(code: string): boolean {
  return /^(ซ|จ)\.\d{3,}$/.test(String(code || '').trim());
}

export function isOverdueProject(
  project: Pick<ProjectRecord, 'status' | 'due'>,
  day: string = todayBangkok(),
): boolean {
  return isActiveProject(project) && Boolean(project.due) && project.due < day;
}

export function sortProjects(
  rows: ProjectRecord[],
  key: SortKey,
  dir: SortDirection = 'asc',
): ProjectRecord[] {
  const factor = dir === 'asc' ? 1 : -1;
  const numericKeys: SortKey[] = ['budget', 'agreed', 'year'];
  return [...rows].sort((a, b) => {
    const x = a[key] ?? '';
    const y = b[key] ?? '';
    if (numericKeys.includes(key)) {
      return (Number(x) - Number(y)) * factor;
    }
    return String(x).localeCompare(String(y), 'th', { numeric: true }) * factor;
  });
}

